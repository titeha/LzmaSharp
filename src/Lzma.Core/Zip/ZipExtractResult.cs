namespace Lzma.Core.Zip;

/// <summary>
/// Результат распаковки ZIP-архива на диск.
/// </summary>
public enum ZipExtractResult
{
  /// <summary>Все элементы успешно записаны.</summary>
  Ok = 0,

  /// <summary>Небезопасный/конфликтующий путь, дубли или существующий файл без разрешения на перезапись.</summary>
  InvalidData = 1,

  /// <summary>Ошибка ввода-вывода при записи на диск.</summary>
  IOError = 2,

  /// <summary>Зашифрованный архив: неверный пароль либо пароль не задан.</summary>
  WrongPassword = 3,

  /// <summary>
  /// На томе назначения недостаточно свободного места для распаковываемых данных.
  /// Возвращается до первой записи на диск; существующие файлы не изменяются.
  /// Оценка требуемого объёма приближённая: сумма распакованных размеров без запаса и без учёта
  /// накладных расходов файловой системы (блоки, записи каталогов). Измерение свободного места —
  /// best-effort: если том не определён или не готов, проверка пропускается и операция выполняется.
  /// Потребитель, не распознающий это значение, обязан трактовать любой результат, отличный от
  /// <see cref="Ok"/>, как отказ.
  /// </summary>
  InsufficientSpace = 4,

  /// <summary>
  /// Путь назначения, каталога или имени временного/backup-файла превышает лимит, принятый
  /// в реализации: Windows — 32759 (документированный предел расширенного пути 32767 минус
  /// запас 8 на префикс <c>\\?\</c> / <c>\\?\UNC\</c>), macOS — <c>MAXPATHLEN</c> (1024),
  /// прочие POSIX — <c>PATH_MAX</c> (4096); отдельный компонент имени — 255 (на POSIX
  /// измеряется в байтах UTF-8). Проверка строгая: отказ при «длина + суффикс ≥ лимита» для
  /// полного пути и при «&gt; 255» для компонента, поэтому для файла (суффикс стадии 21 символ)
  /// предельная длина пути на 22 символа меньше лимита, для каталога — на 1 символ.
  /// Возвращается до первой записи на диск; существующие файлы не изменяются.
  /// Фактические <c>NAME_MAX</c>/<c>PATH_MAX</c> на ubuntu/macos локально не измерены
  /// (capability-probe — отдельная задача).
  /// Потребитель, не распознающий это значение, обязан трактовать любой результат, отличный от
  /// <see cref="Ok"/>, как отказ.
  /// </summary>
  PathTooLong = 5,
}
