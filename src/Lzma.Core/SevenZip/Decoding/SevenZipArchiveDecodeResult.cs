namespace Lzma.Core.SevenZip;

/// <summary>
/// Результат декодирования 7z-архива.
/// </summary>
public enum SevenZipArchiveDecodeResult
{
  Ok,
  NeedMoreData,
  InvalidData,
  NotSupported,

  /// <summary>
  /// Внутренняя ошибка (неожиданное состояние).
  /// </summary>
  InternalError,

  /// <summary>
  /// На томе назначения недостаточно свободного места для распаковываемых данных.
  /// Возвращается до первой записи на диск (кроме root-каталога, который создаётся ранее
  /// и удаляется откатом через <c>StagedExtractionJournal.Rollback</c>);
  /// существующие файлы не изменяются.
  /// Оценка требуемого объёма приближённая: сумма распакованных размеров выбранных
  /// не-каталогов без запаса и без учёта накладных расходов файловой системы
  /// (блоки, записи каталогов). Значения ≤ 0 из недоверенного заголовка пропускаются,
  /// сумма насыщается до <see cref="long.MaxValue"/>.
  /// Измерение свободного места — best-effort: если том не определён или не готов,
  /// проверка пропускается и операция выполняется.
  /// Потребитель, не распознающий это значение, обязан трактовать любой результат,
  /// отличный от <see cref="Ok"/>, как отказ.
  /// </summary>
  InsufficientSpace,

  /// <summary>
  /// Путь записи архива (включая её каталоги) или имени файла-стадии превышает лимит,
  /// принятый в реализации: Windows — 32759 (документированный предел расширенного пути
  /// 32767 минус запас на префикс <c>\\?\</c>), macOS — <c>MAXPATHLEN</c> (1024),
  /// прочие POSIX — <c>PATH_MAX</c> (4096); отдельный компонент имени — 255
  /// (на POSIX измеряется в байтах UTF-8). Проверка учитывает суффикс стадии:
  /// к последнему компоненту имени файла добавляется 21 символ, поэтому предельный
  /// компонент имени файла со стадией — 234.
  /// Возвращается до первой записи данных; существующие файлы не изменяются.
  /// Root-каталог назначения создаётся до проверки и при отказе удаляется откатом
  /// (<c>StagedExtractionJournal.Rollback</c>); если лимит превышает сам путь назначения,
  /// создание root отказывает на уровне ОС раньше и возвращается <see cref="InternalError"/>
  /// (известный долг до шага G4).
  /// Потребитель, не распознающий это значение, обязан трактовать любой результат,
  /// отличный от <see cref="Ok"/>, как отказ.
  /// </summary>
  PathTooLong,
}
